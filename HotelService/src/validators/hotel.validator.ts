import { z } from "zod";

// Validates the fields clients must provide when creating a hotel.
export const createHotelSchema = z.object({
    name: z
        .string()
        .trim()
        .min(1, "hotel name is required")
        .max(100, "hotel name must be less than 100 characters"),

    address: z.string().trim().min(1, "hotel address is required"),

    location: z
        .string()
        .trim()
        .min(1, "hotel location is required")
        .max(100, "hotel location must be less than 100 characters"),

    rating: z
        .number()   
        .min(0, "rating cannot be less than 0")
        .max(5, "rating cannot be greater than 5")
        .default(0),
    // Uses 0 when the client does not provide a rating.

    ratingCount: z
        .number()
        .int()
        .nonnegative("rating count cannot be negative")
        .default(0),
    // Uses 0 when the client does not provide a rating count.

    /**
     * Example hotel creation request:
     *
     * {
     *   "name": "Taj Hotel",
     *   "address": "Apollo Bunder, Mumbai",
     *   "location": "Mumbai",
     *   "rating": 4.5,
     *   "ratingCount": 120
     * }
     *
     * The client does not need to provide:
     * - id: generated automatically as a UUID.
     * - createdAt: generated by the database.
     * - updatedAt: generated by the database on creation.
     * - deletedAt: remains null until the hotel is soft-deleted.
     */
});

export const updateHotelSchema = createHotelSchema
    .partial()
    .refine((data) => Object.keys(data).length > 0, {
        message: "at least one field must be provided for an update",
    });

// Validates the UUID supplied through hotel route parameters.
export const hotelIdSchema = z.object({
    id: z.uuid("invalid hotel id"),
});
